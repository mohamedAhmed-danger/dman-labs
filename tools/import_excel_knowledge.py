"""
bulk_import_tests.py

Bulk-insert lab tests from an Excel file using the same pipeline as the admin form:
    generate_test()  ->  TestsService.create_lab_service()

Uniform catalog design: each test is created ONCE per laboratory; prices per city
go to lab_service_city_prices (and Qdrant gets ONE vector per test, in tests_lab{id}).

Excel layout (first row = headers, matched case-insensitively):
    Test Name           | name of the test                          (required)
    Type                | optional, ignored
    Price               | DEFAULT price, used for cities without their own price (optional)
    <city>              | one column per city, header = the city's name (or one of its aliases)
                          empty cell = no price for that city (test unavailable there,
                          unless a default Price exists)
    Duration (days)     | optional. Taken from Excel (overrides the AI value)
    تعليمات المريض ...   | optional. Patient instructions taken from Excel (overrides the AI value)
Every row needs a Price or at least one city price.

What comes from where:
    Excel -> prices, duration, patient_instructions   (AI value is used only if the Excel cell is empty)
    AI    -> description, sample_type, keywords, alias_name

Usage:
    python bulk_import_tests.py --limit 5 --dry-run    # check parsing + AI output only
    python bulk_import_tests.py --limit 5              # real insert of 5 rows
    python bulk_import_tests.py                        # everything

Resume: if the script stops, run it again. Tests that already exist (same lab + name)
are NOT regenerated by the AI; only their prices are refreshed from the Excel
(add --update-existing-details to also overwrite their duration + patient instructions).

    python bulk_import_tests.py --check-existing       # just count how many rows are new vs already in the DB
"""

