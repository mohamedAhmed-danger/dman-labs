import csv
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import openpyxl

try:
    from app import app  # noqa: E402
except ImportError:
    from app import create_app  # noqa: E402
    app = create_app()

from models.models import db, Laboratory, City, LabService  # noqa: E402
import services.domain.tests_service as tests_service_module  # noqa: E402
from services.domain.tests_service import TestsService  # noqa: E402
from services.shared.generation_service import generate_test  # noqa: E402
from services.shared.vector_service import upsert_test_vector as _real_upsert_test_vector  # noqa: E402
from utils.embedding_utils import build_embedding_text  # noqa: E402

DEFAULT_EXCEL_PATH = "Unified_Prices.xlsx"
FAILED_LOG_PATH = "failed_tests.csv"
DEFAULT_DETAIL_LOG_PATH = "import_log.txt"
SLEEP_BETWEEN_CALLS = 1.0

# Excel stores duration in DAYS, while LabService.duration is stored in HOURS.
# Excel duration always takes precedence when it is present.

NAME_HEADERS = {"test name", "testname", "name", "test", "اسم التحليل", "التحليل", "الاسم"}
TYPE_HEADERS = {"type", "النوع"}
PRICE_HEADERS = {"price", "default price", "السعر", "السعر الافتراضي"}
DURATION_HEADERS = {"duration (days)", "duration", "المدة", "المدة (أيام)", "مدة التحليل"}
INSTRUCTIONS_HEADERS = {
    "patient instructions", "instructions", "تعليمات المريض", "تعليمات",
    "chatbot: تعليمات المريض قبل العينة",
}
# Columns that exist in the file but are not used: silently ignored (no warning)
IGNORED_HEADERS = {"نوع التحضير", "preparation type"}


def _norm(value) -> str:
    text = str(value or "").strip().lower()
    for src_ch, dst_ch in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ى", "ي")):
        text = text.replace(src_ch, dst_ch)
    return " ".join(text.split())


def parse_price(value):
    """Returns a float, or None for an empty/invalid cell."""
    if value is None or str(value).strip() == "":
        return None
    try:
        price = float(str(value).replace(",", "").strip())
    except ValueError:
        return None
    return price if price >= 0 else None


def parse_duration_days(value):
    """Returns the number of days (int when whole, else float), or None for an empty/invalid cell."""
    if value is None or str(value).strip() == "":
        return None
    try:
        days = float(str(value).replace(",", "").strip())
    except ValueError:
        return None
    if days < 0:
        return None
    return int(days) if days == int(days) else days


def parse_text(value):
    """Returns stripped text, or None for an empty cell."""
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def duration_days_to_hours(days):
    """Convert an Excel duration in days to integer hours for LabService.duration."""
    if days is None:
        return None
    return int(round(float(days) * 24))


def resolve_duration(excel_days, ai_value):
    """Excel wins: convert its duration from days to hours; otherwise keep the AI value."""
    if excel_days is None:
        return ai_value
    return duration_days_to_hours(excel_days)


def get_target_laboratory(lab_id=None):
    if lab_id:
        lab = db.session.get(Laboratory, lab_id)
    else:
        lab = Laboratory.query.order_by(Laboratory.id.asc()).first()
    if not lab:
        raise RuntimeError("Laboratory not found. Create one first (or pass a valid --lab-id).")
    return lab


def build_city_lookup(laboratory_id: int) -> dict:
    """{normalized city name or alias: city_id} for the laboratory."""
    lookup = {}
    for city in City.query.filter_by(laboratory_id=laboratory_id).all():
        lookup[_norm(city.name)] = city.id
        for alias in (city.aliases or []):
            lookup.setdefault(_norm(alias), city.id)
    return lookup


def read_excel_rows(excel_path: str, city_lookup: dict):
    """
    Returns (rows, warnings).
    row = {"type", "name", "default_price", "city_prices": {city_id: price},
           "duration_days", "instructions", "row": excel row number}
    """
    wb = openpyxl.load_workbook(excel_path, data_only=True)
    ws = wb.active
    header = [_norm(c) for c in next(ws.iter_rows(min_row=1, max_row=1, values_only=True))]

    name_col = type_col = price_col = duration_col = instructions_col = None
    city_cols = {}      # column index -> city_id
    warnings = []
    for idx, title in enumerate(header):
        if not title:
            continue
        if title in NAME_HEADERS and name_col is None:
            name_col = idx
        elif title in TYPE_HEADERS and type_col is None:
            type_col = idx
        elif title in PRICE_HEADERS and price_col is None:
            price_col = idx
        elif title in DURATION_HEADERS and duration_col is None:
            duration_col = idx
        elif (title in INSTRUCTIONS_HEADERS or "تعليمات" in title) and instructions_col is None:
            instructions_col = idx
        elif title in city_lookup:
            city_cols[idx] = city_lookup[title]
        elif title in IGNORED_HEADERS or title.startswith("test code"):
            continue
        else:
            warnings.append(f"Column '{title}' is not recognised and was ignored")

    if name_col is None:
        raise ValueError("No test-name column found (expected a header like 'Test Name').")
    if price_col is None and not city_cols:
        raise ValueError("No price column found (expected 'Price' and/or one column per city).")
    if duration_col is None:
        warnings.append("No duration column found - duration will come from the AI")
    if instructions_col is None:
        warnings.append("No patient-instructions column found - instructions will come from the AI")

    def cell(row, idx):
        return row[idx] if idx is not None and idx < len(row) else None

    rows = []
    for excel_row, row in enumerate(ws.iter_rows(min_row=2, values_only=True), start=2):
        name = cell(row, name_col)
        if not name or not str(name).strip():
            continue
        city_prices = {}
        for idx, city_id in city_cols.items():
            price = parse_price(cell(row, idx))
            if price is not None:
                city_prices[city_id] = price
        rows.append({
            "type": cell(row, type_col),
            "name": str(name).strip(),
            "default_price": parse_price(cell(row, price_col)),
            "city_prices": city_prices,
            "duration_days": parse_duration_days(cell(row, duration_col)),
            "instructions": parse_text(cell(row, instructions_col)),
            "row": excel_row,
        })
    return rows, warnings


def log_failure(name: str, error: str):
    file_exists = Path(FAILED_LOG_PATH).exists()
    with open(FAILED_LOG_PATH, "a", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        if not file_exists:
            writer.writerow(["name", "error"])
        writer.writerow([name, error])


def generation_result_to_dict(generated) -> dict:
    if hasattr(generated, "model_dump"):
        return generated.model_dump()
    return generated.dict()


def format_list(value) -> str:
    return "[" + ", ".join(str(v) for v in value) + "]" if value else "[]"


def write_detail_log(log_path, index, total, name, generated_dict, embed_text,
                     db_fields, db_status, qdrant_payload, qdrant_status):
    lines = ["=" * 70, f"[{index}/{total}] {name}", "=" * 70, "AI generation:"]
    if generated_dict is None:
        lines.append("  (not generated)")
    else:
        for key in ("description", "patient_instructions", "duration", "sample_type"):
            lines.append(f"  {key:<20}: {generated_dict.get(key)}")
        lines.append(f"  {'keywords':<20}: {format_list(generated_dict.get('keywords'))}")
        lines.append(f"  {'alias_name':<20}: {format_list(generated_dict.get('alias_name'))}")
    lines += ["", "Embedding text:", f'  "{embed_text}"' if embed_text else "  (not computed)", "",
              "Saved to DB (LabService):"]
    if db_fields is None:
        lines.append("  (not saved)")
    else:
        for key, val in db_fields.items():
            lines.append(f"  {key:<20}: {format_list(val) if isinstance(val, list) else val}")
    lines += [f"  status: {db_status}", "", "Qdrant payload:"]
    if qdrant_payload is None:
        lines.append("  (none)")
    else:
        for key, val in qdrant_payload.items():
            lines.append(f"  {key:<14}: {val}")
    lines += [f"  status: {qdrant_status}", "", ""]
    with open(log_path, "a", encoding="utf-8-sig") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description="Bulk import lab tests from Excel with AI generation")
    parser.add_argument("--excel", default=DEFAULT_EXCEL_PATH)
    parser.add_argument("--lab-id", type=int, default=None, help="Laboratory id (default: first laboratory)")
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--sleep", type=float, default=SLEEP_BETWEEN_CALLS)
    parser.add_argument("--dry-run", action="store_true", help="Parse + generate with AI, write nothing")
    parser.add_argument("--skip-vectors", action="store_true",
                        help="Save to SQL only; tests are marked sync_status='pending' so they can be indexed later")
    parser.add_argument("--log-file", default=DEFAULT_DETAIL_LOG_PATH)
    parser.add_argument("--check-existing", action="store_true",
                        help="No AI, no writes: only report how many Excel rows are new vs already in the DB")
    parser.add_argument("--update-existing-details", action="store_true",
                        help="For tests that already exist, ALSO overwrite duration + patient instructions from the Excel")
    args = parser.parse_args()

    if not Path(args.excel).exists():
        print(f"File not found: {args.excel}")
        sys.exit(1)

    last_qdrant_call = {}

    def logged_upsert_test_vector(test_id, test_name, description, keywords, laboratory_id):
        """Replaces the function TestsService calls, to log it.
        It RE-RAISES on failure/skip so create_lab_service marks the test 'pending' (re-indexable)
        instead of wrongly saying 'ok'."""
        try:
            embed_text = build_embedding_text(test_name, description or "", keywords or [])
        except Exception as e:
            embed_text = f"<could not build embedding text: {e}>"
        payload = {"service_id": test_id, "name": test_name, "laboratory_id": laboratory_id}

        if args.skip_vectors:
            last_qdrant_call.update(embed_text=embed_text, payload=payload, status="skipped (--skip-vectors) -> pending")
            raise RuntimeError("vector upsert skipped (--skip-vectors)")
        try:
            _real_upsert_test_vector(test_id, test_name, description, keywords, laboratory_id=laboratory_id)
            last_qdrant_call.update(embed_text=embed_text, payload=payload, status="upsert OK")
        except Exception as e:
            last_qdrant_call.update(embed_text=embed_text, payload=payload, status=f"FAILED: {e} -> pending")
            raise

    tests_service_module.upsert_test_vector = logged_upsert_test_vector

    with app.app_context():
        lab = get_target_laboratory(args.lab_id)
        city_lookup = build_city_lookup(lab.id)
        id_to_city = {c.id: c.name for c in City.query.filter_by(laboratory_id=lab.id).all()}
        print(f"Laboratory: {lab.name} (id={lab.id}) | cities: {', '.join(id_to_city.values()) or 'NONE'}")
        if not id_to_city:
            print("This laboratory has no cities. Create them first.")
            sys.exit(1)

        rows, warnings = read_excel_rows(args.excel, city_lookup)
        for w in warnings:
            print(f"WARNING: {w}")
        if args.check_existing:
            db_names = {n for (n,) in db.session.query(LabService.name).filter_by(laboratory_id=lab.id).all()}
            new_names = [r["name"] for r in rows if r["name"] not in db_names]
            print(f"Excel rows: {len(rows)} | already in DB: {len(rows) - len(new_names)} | NEW: {len(new_names)}")
            for n in new_names[:15]:
                print(f"  new: {n}")
            if len(new_names) > 15:
                print(f"  ... and {len(new_names) - 15} more")
            return
        if args.limit:
            rows = rows[: args.limit]
        total = len(rows)
        print(f"Rows to process: {total}")

        created = prices_updated = unchanged = failed = 0

        try:
            for i, row in enumerate(rows, start=1):
                name = row["name"]
                default_price = row["default_price"]
                city_prices = row["city_prices"]
                print(f"[{i}/{total}] {name} ...", end=" ")

                if default_price is None and not city_prices:
                    print("no price in this row - skipped")
                    log_failure(name, f"row {row['row']}: no default price and no city price")
                    failed += 1
                    continue

                existing = LabService.query.filter_by(laboratory_id=lab.id, name=name).first()
                if existing:
                    # No AI call. Prices are always refreshed; duration + instructions only with --update-existing-details.
                    cur_duration = getattr(existing, "duration", None)
                    cur_instr = getattr(existing, "patient_instructions", None) or getattr(existing, "instructions", None)
                    detail_changes = []
                    if args.update_existing_details:
                        excel_hours = duration_days_to_hours(row["duration_days"])
                        if excel_hours is not None and excel_hours != cur_duration:
                            detail_changes.append(f"duration {cur_duration} -> {excel_hours} hours")
                        if row["instructions"] and row["instructions"] != (cur_instr or "").strip():
                            detail_changes.append("instructions")
                    if args.dry_run:
                        extra = f" | would update: {', '.join(detail_changes)}" if detail_changes else ""
                        print(f"exists (dry-run){extra}")
                        unchanged += 1
                        continue
                    extra_fields = {}
                    if args.update_existing_details:
                        if row["duration_days"] is not None:
                            extra_fields["duration"] = duration_days_to_hours(row["duration_days"])
                        if row["instructions"]:
                            extra_fields["instructions"] = row["instructions"]
                    svc = TestsService(laboratory_id=lab.id)
                    updated, message = svc.update_test(
                        test_id=existing.id,
                        price=default_price,
                        city_prices={cid: p for cid, p in city_prices.items()},
                        **extra_fields,
                    )
                    if updated is None:
                        print(f"update failed: {message}")
                        log_failure(name, message)
                        failed += 1
                    else:
                        print("exists - prices refreshed" + (" + details" if extra_fields else ""))
                        prices_updated += 1
                    continue

                generated_dict = db_fields = None
                db_status = "(not saved)"
                last_qdrant_call.clear()
                try:
                    generated = generate_test(name=name)
                    generated_dict = generation_result_to_dict(generated)

                    # Excel wins for duration + patient instructions; AI is the fallback for empty cells.
                    final_duration = resolve_duration(row["duration_days"], generated.duration)
                    final_instructions = row["instructions"] or generated.patient_instructions

                    db_fields = {
                        "laboratory_id": lab.id,
                        "name": name,
                        "default_price": default_price,
                        "city_prices": {id_to_city.get(cid, cid): p for cid, p in city_prices.items()},
                        "description": generated.description,
                        "patient_instructions": final_instructions,
                        "duration": final_duration,
                        "sample_type": generated.sample_type,
                        "keywords": generated.keywords,
                        "alias_name": generated.alias_name,
                        "from_excel": ", ".join(
                            k for k, v in (("duration", row["duration_days"]),
                                           ("patient_instructions", row["instructions"])) if v is not None
                        ) or "(nothing - AI fallback used)",
                    }

                    if args.dry_run:
                        embed_text = build_embedding_text(name, generated.description or "", generated.keywords or [])
                        last_qdrant_call.update(
                            embed_text=embed_text,
                            payload={"service_id": None, "name": name, "laboratory_id": lab.id},
                            status="(dry-run)")
                        print("generated (dry-run)")
                        created += 1
                        write_detail_log(args.log_file, i, total, name, generated_dict,
                                         last_qdrant_call.get("embed_text"), db_fields,
                                         "(dry-run - nothing saved)",
                                         last_qdrant_call.get("payload"), last_qdrant_call.get("status"))
                        time.sleep(args.sleep)
                        continue

                    svc = TestsService(laboratory_id=lab.id)
                    new_test, message = svc.create_lab_service(
                        name=name,
                        price=default_price,
                        city_prices=city_prices,
                        description=generated.description,
                        patient_instructions=final_instructions,
                        duration=final_duration,
                        sample_type=generated.sample_type,
                        keywords=generated.keywords,
                        alias_name=generated.alias_name,
                    )
                    if new_test:
                        status = new_test.sync_status
                        print("created" if status == "ok" else f"created (vector {status})")
                        db_status = f"saved (sync_status={status})"
                        created += 1
                    else:
                        print(f"failed: {message}")
                        db_status = f"FAILED: {message}"
                        log_failure(name, message)
                        failed += 1

                    write_detail_log(args.log_file, i, total, name, generated_dict,
                                     last_qdrant_call.get("embed_text"), db_fields, db_status,
                                     last_qdrant_call.get("payload"),
                                     last_qdrant_call.get("status", "(not called)"))
                except KeyboardInterrupt:
                    raise
                except Exception as e:
                    db.session.rollback()
                    print(f"Exception: {e}")
                    log_failure(name, str(e))
                    write_detail_log(args.log_file, i, total, name, generated_dict,
                                     last_qdrant_call.get("embed_text"), db_fields, f"Exception: {e}",
                                     last_qdrant_call.get("payload"),
                                     last_qdrant_call.get("status", "(not called)"))
                    failed += 1

                time.sleep(args.sleep)

        except KeyboardInterrupt:
            print("\nStopped (Ctrl+C). Progress is saved - run the same command again to resume.")

        print("\n----------------------------------------")
        print(f"created:          {created}")
        print(f"prices refreshed: {prices_updated}")
        print(f"unchanged:        {unchanged}")
        print(f"failed:           {failed}")
        if failed:
            print(f"see: {FAILED_LOG_PATH}")
        print(f"details: {args.log_file}")
        print("----------------------------------------")


if __name__ == "__main__":
    main()
